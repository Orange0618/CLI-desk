const { contextBridge, ipcRenderer, webUtils } = require('electron');

contextBridge.exposeInMainWorld('api', {
  getSessions: () => ipcRenderer.invoke('sessions:get'),
  onSessionsUpdate: cb => ipcRenderer.on('sessions:update', (_e, s) => cb(s)),

  resume: opts => ipcRenderer.invoke('pty:resume', opts),
  newSession: opts => ipcRenderer.invoke('pty:new', opts),
  write: (id, data) => ipcRenderer.send('pty:write', id, data),
  resize: (id, cols, rows) => ipcRenderer.send('pty:resize', id, cols, rows),
  kill: id => ipcRenderer.invoke('pty:kill', id),
  onData: cb => ipcRenderer.on('pty:data', (_e, id, d) => cb(id, d)),
  onExit: cb => ipcRenderer.on('pty:exit', (_e, id, code) => cb(id, code)),

  setConfig: patch => ipcRenderer.invoke('config:set', patch),
  deleteSession: id => ipcRenderer.invoke('session:delete', id),
  getUsage: () => ipcRenderer.invoke('usage:get'),
  fileResolve: q => ipcRenderer.invoke('file:resolve', q),
  qlStatus: () => ipcRenderer.invoke('ql:status'),
  qlOpenWeb: url => ipcRenderer.invoke('ql:openWeb', url),
  qlAnchor: (hwnd, rc) => ipcRenderer.send('ql:anchor', hwnd, rc),
  qlShow: (hwnd, visible) => ipcRenderer.send('ql:show', hwnd, visible),
  qlNav: (hwnd, n) => ipcRenderer.send('ql:nav', hwnd, n),
  qlClose: hwnd => ipcRenderer.invoke('ql:close', hwnd),
  qlPopout: hwnd => ipcRenderer.invoke('ql:popout', hwnd),
  onQlEvent: cb => ipcRenderer.on('ql:event', (_e, ev) => cb(ev)),
  onQlOpenUrl: cb => ipcRenderer.on('ql:openUrl', (_e, url) => cb(url)),
  openInEgo: url => ipcRenderer.invoke('link:openInEgo', url),
  readFile: p => ipcRenderer.invoke('file:read', p),
  watchFile: p => ipcRenderer.invoke('file:watch', p),
  onFileChanged: cb => ipcRenderer.on('file:changed', (_e, info) => cb(info)),
  showItem: p => ipcRenderer.invoke('shell:showItem', p),
  openExternal: url => ipcRenderer.invoke('shell:openExternal', url, 'system'),
  enableUsage: () => ipcRenderer.invoke('usage:enable'),
  onUsageUpdate: cb => ipcRenderer.on('usage:update', (_e, u) => cb(u)),
  pickFolder: () => ipcRenderer.invoke('dialog:pickFolder'),
  openPath: p => ipcRenderer.invoke('shell:openPath', p),
  readClipboard: () => ipcRenderer.invoke('clipboard:readText'),
  writeClipboard: t => ipcRenderer.invoke('clipboard:writeText', t),
  clipboardHasImage: () => ipcRenderer.invoke('clipboard:hasImage'),
  normCwd: p => ipcRenderer.invoke('util:normCwd', p),
  // 拖进来的文件拿到真实路径（Electron 32+ 不再有 File.path）
  pathForFile: f => { try { return webUtils.getPathForFile(f); } catch { return ''; } },
  onThemeUpdated: cb => ipcRenderer.on('theme:updated', (_e, dark) => cb(dark)),
  setOverlay: (color, symbolColor) => ipcRenderer.send('window:overlay', color, symbolColor),
});
